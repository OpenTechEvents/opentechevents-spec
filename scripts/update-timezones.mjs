#!/usr/bin/env node
/**
 * Regenerates $defs.timezone's enum in the current spec version's event.schema.json from the official IANA tzdata
 * release — NOT from `Intl.supportedValuesOf('timeZone')`. That API's notion of "canonical" name
 * tracks whatever tzdata snapshot the running Node/ICU bundles, and two Node versions can disagree
 * on which of an old/new pair (e.g. Europe/Kiev vs Europe/Kyiv, renamed 2022) counts as canonical —
 * regenerating the enum on a different machine could silently flip which documents validate. The
 * tzdata release itself does not have that problem: it lists every Zone AND every historical Link
 * (alias), so both old and new names stay valid regardless of who runs this script or when.
 *
 * Maintenance script, not part of `npm run validate` or CI: run by hand when a new tzdata release
 * adds a zone (rare — see https://www.iana.org/time-zones for release notes).
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/**
 * Which spec version to write to: the highest `spec/vN.N/` by default, `--spec vN.N` to target an
 * older one deliberately. This used to be hardcoded, and the hardcoded value was `v0.4` — so long
 * after v0.5 shipped, running this script silently rewrote a FROZEN version, with whatever
 * upstream data had been released since, and left the version under development untouched.
 * `AGENTS.md`'s fork procedure depends on this resolving correctly: regenerating the enums into
 * the NEW version is the integrity check that proves the copy was faithful. Same resolution as
 * scripts/update-licenses.mjs, which always had it right.
 */
function specArg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? undefined : process.argv[i + 1];
}

const specDir = new URL("../spec/", import.meta.url);
const specVersion =
  specArg("spec") ??
  readdirSync(specDir)
    .filter((n) => /^v\d+\.\d+$/.test(n))
    .sort((a, b) => {
      const [aM, aN] = a.slice(1).split(".").map(Number);
      const [bM, bN] = b.slice(1).split(".").map(Number);
      return aM - bM || aN - bN;
    })
    .at(-1);
const SCHEMA_PATH = new URL(`${specVersion}/event.schema.json`, specDir);
const RELEASE_URL = "https://data.iana.org/time-zones/tzdata-latest.tar.gz";
// Zone/Link definitions live in these files; "factory" only defines the "Factory" placeholder
// zone, a deliberate "no real timezone was given" sentinel, not a real geographic identifier.
const ZONE_FILES = [
  "backward",
  "africa",
  "antarctica",
  "asia",
  "australasia",
  "etcetera",
  "europe",
  "northamerica",
  "southamerica",
];

const workDir = mkdtempSync(join(tmpdir(), "ote-tzdata-"));
try {
  const tarball = join(workDir, "tzdata.tar.gz");
  const res = await fetch(RELEASE_URL);
  if (!res.ok) throw new Error(`fetch ${RELEASE_URL} failed: ${res.status}`);
  writeFileSync(tarball, Buffer.from(await res.arrayBuffer()));
  execFileSync("tar", ["-xzf", tarball, "-C", workDir]);

  const version = readFileSync(join(workDir, "version"), "utf8").trim();

  const names = new Set(["UTC"]);
  for (const file of ZONE_FILES) {
    const text = readFileSync(join(workDir, file), "utf8");
    for (const line of text.split("\n")) {
      const fields = line.split("#")[0].trim().split(/\s+/);
      if (fields[0] === "Zone") names.add(fields[1]);
      if (fields[0] === "Link") {
        names.add(fields[1]); // LINK-FROM: the canonical target
        names.add(fields[2]); // LINK-TO: the alias name that resolves to it
      }
    }
  }

  const sorted = [...names].sort((a, b) => a.localeCompare(b));

  const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
  const timezone = schema.$defs.event.properties.timezone;
  timezone.enum = sorted;
  timezone.$comment = `Generated by scripts/update-timezones.mjs from IANA tzdata ${version} (https://www.iana.org/time-zones). Every Zone and Link (alias), so a historical rename (e.g. Europe/Kiev → Europe/Kyiv, 2022) never invalidates a document that used the old name.`;
  writeFileSync(SCHEMA_PATH, JSON.stringify(schema, null, 2) + "\n");

  console.log(`tzdata ${version}: ${sorted.length} identifiers (canonical + historical aliases)`);
  console.log(`Updated ${SCHEMA_PATH.pathname}`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
